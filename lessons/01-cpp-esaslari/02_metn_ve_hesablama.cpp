#include <iostream>

using namespace std;

int main() {
    // 1. Mətn və ədədin fərqi
    cout << "5 + 3" << endl; // Dırnaq içində olduqda mətn kimi çıxır
    cout << 5 + 3 << endl;   // Dırnaqsız yazıldıqda hesablanıb 8 çıxır

    // 2. Mətn və hesablama nəticəsinin zəncirvari çıxarılması
    cout << "10 ve 20 ededlerinin cemi: " << 10 + 20 << endl;
    cout << "Düzbucaqlının sahəsi (6 * 4): " << 6 * 4 << endl;

    return 0;
}
